save_png <- function(plot, filename, width, height) {
  # Draw outside the synced project folder and copy the finished PNG into it.
  tmp <- tempfile(fileext = ".png")
  on.exit(unlink(tmp), add = TRUE)
  ggplot2::ggsave(tmp, plot = plot, width = width, height = height,
                  dpi = 300, bg = "white", device = grDevices::png)
  if (!file.copy(tmp, filename, overwrite = TRUE)) {
    stop("Could not update ", filename,
         ". Close the image if open and check whether OneDrive is syncing it.")
  }
}

